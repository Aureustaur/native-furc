//! Furcadia avatar color palette, gradient LUT builder, color-code parser,
//! and FOX5 `B == 0` green-channel pixel remapping extracted from Furcadia.exe + palette.act.

/// Decoded avatar appearance parsed from a Furcadia color string (`w...`, `t...`, `u...`, etc.).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AvatarAppearance {
    pub fur: u8,
    pub markings: u8,
    pub hair: u8,
    pub eyes: u8,
    pub badge: u8,
    pub vest: u8,
    pub bracers: u8,
    pub cape: u8,
    pub boots: u8,
    pub trousers: u8,
    pub wings: u8,
    pub accent: u8,
    pub gender: u8,
    pub species_id: u16,
    /// Normalized cache key for the 12 color slots.
    pub color_key: [u8; 12],
}

impl Default for AvatarAppearance {
    fn default() -> Self {
        Self {
            fur: 0,
            markings: 0,
            hair: 0,
            eyes: 0,
            badge: 0,
            vest: 0,
            bracers: 0,
            cape: 0,
            boots: 0,
            trousers: 0,
            wings: 0,
            accent: 0,
            gender: 0,
            species_id: 1,
            color_key: [0; 12],
        }
    }
}

/// Updates `app` from a raw Furcadia color-code byte slice matching `Furcadia.exe` `0x406880`.
/// Returns `Some(consumed_bytes)` on success or `None` if fewer bytes than required
/// for the color header/slots are available.
///
/// Short codes (`13`-byte `'w'`, `11`-byte `'t'`, or `10`-byte legacy) update color
/// slots while leaving `app.gender` and `app.species_id` unchanged, matching `0x4069dc`.
pub fn apply_color_bytes(app: &mut AvatarAppearance, bytes: &[u8]) -> Option<usize> {
    let n = bytes.len().min(63);
    if n == 0 {
        return None;
    }

    if matches!(bytes[0], b'u' | b'v') {
        app.fur = 0;
        app.markings = 0;
        app.hair = 0;
        app.eyes = 0;
        app.badge = 0;
        app.vest = 0;
        app.bracers = 0;
        app.cape = 0;
        app.boots = 0;
        app.trousers = 0;
        app.wings = 0;
        app.accent = 0;
        app.color_key = [0; 12];
        app.gender = 0;
        app.species_id = 1;
        if n >= 3 {
            let g = (bytes[0] as i32 - 35) & 3;
            if (0..=2).contains(&g) {
                app.gender = g as u8;
            }
            let sp = (bytes[1] as i32 - 35) + 1;
            if sp >= 0 {
                app.species_id = sp as u16;
            }
            return Some(3);
        }
        return Some(0);
    }

    let (offset, num_slots, mut pos) = match bytes[0] {
        b'w' => (35i32, 12usize, 1usize),
        b't' => (35i32, 10usize, 1usize),
        _ => (32i32, 10usize, 0usize),
    };

    if n - pos < num_slots {
        return None;
    }

    let mut slots = app.color_key;
    for i in 0..num_slots {
        let val = bytes[pos + i] as i32 - offset;
        if val >= 0 {
            slots[i] = val as u8;
        }
    }
    for slot in &mut slots[num_slots..] {
        *slot = 0;
    }
    pos += num_slots;

    app.fur = slots[0];
    app.markings = slots[1];
    app.hair = slots[2];
    app.eyes = slots[3];
    app.badge = slots[4];
    app.vest = slots[5];
    app.bracers = slots[6];
    app.cape = slots[7];
    app.boots = slots[8];
    app.trousers = slots[9];
    app.wings = slots[10];
    app.accent = slots[11];
    app.color_key = slots;

    if pos + 3 <= n {
        let g = (bytes[pos] as i32 - offset) & 3;
        if (0..=2).contains(&g) {
            app.gender = g as u8;
        }
        if bytes[0] == b'w' {
            let lo = bytes[pos + 1] as i32 - offset;
            let hi = bytes[pos + 2] as i32 - offset;
            let sp = hi * 220 + lo;
            if sp >= 0 {
                app.species_id = sp as u16;
            }
        } else {
            let sp = (bytes[pos + 1] as i32 - offset) + 1;
            if sp >= 0 {
                app.species_id = sp as u16;
            }
        }
        pos += 3;
    }

    Some(pos)
}

/// Parses a raw Furcadia color-code byte slice, returning `(AvatarAppearance, consumed_bytes)`.
pub fn parse_color_bytes_with_len(bytes: &[u8]) -> Option<(AvatarAppearance, usize)> {
    let mut app = AvatarAppearance::default();
    let len = apply_color_bytes(&mut app, bytes)?;
    Some((app, len))
}

/// Parses a raw Furcadia color-code byte slice (`"w..."`, `"t..."`, `"u..."`, etc.).
/// Falls back to copying available prefix bytes if the slice is shorter than a full record.
pub fn parse_color_bytes(bytes: &[u8]) -> AvatarAppearance {
    if let Some((app, _)) = parse_color_bytes_with_len(bytes) {
        return app;
    }
    let mut app = AvatarAppearance::default();
    if bytes.is_empty() {
        return app;
    }
    let mut slots = [0u8; 12];
    let (offset, start, max_slots) = match bytes[0] {
        b'w' => (35u8, 1usize, 12usize),
        b't' => (35u8, 1usize, 10usize),
        _ => (32u8, 0usize, 10usize),
    };
    for (i, slot) in slots[..max_slots].iter_mut().enumerate() {
        if let Some(&ch) = bytes.get(start + i) {
            *slot = ch.saturating_sub(offset);
        }
    }
    app.fur = slots[0];
    app.markings = slots[1];
    app.hair = slots[2];
    app.eyes = slots[3];
    app.badge = slots[4];
    app.vest = slots[5];
    app.bracers = slots[6];
    app.cape = slots[7];
    app.boots = slots[8];
    app.trousers = slots[9];
    app.wings = slots[10];
    app.accent = slots[11];
    app.color_key = slots;
    app
}

/// Returns the number of bytes `Furcadia.exe` `0x406880` consumes from `bytes`.
pub fn color_code_byte_len(bytes: &[u8]) -> usize {
    parse_color_bytes_with_len(bytes).map(|(_, len)| len).unwrap_or(0)
}

/// Parse a raw Furcadia color code (e.g. `"w..."`, `"t..."`, `"u..."`).
/// Matches `0x406880` in Furcadia.exe:
/// - `'w'`: offset 35 (`'#'`), 12 color slots, gender (`& 3`), 2-byte Base220 species ID (`16` bytes full / `13` bytes color-only).
/// - `'t'`: offset 35 (`'#'`), 10 color slots, gender (`& 3`), 1-byte species + 1 (`14` bytes full / `11` bytes color-only).
/// - `'u'` / `'v'`: reset slots + default gender/species (`3` bytes if `len >= 3`, else `0`).
/// - other: offset 32 (`' '`), 10 color slots (`13` bytes full / `10` bytes color-only).
pub fn parse_color_code(raw: &str) -> AvatarAppearance {
    parse_color_bytes(raw.as_bytes())
}

/// Remap target 256-entry RGB gradient LUTs indexed by green channel `G`.
pub struct RemapLuts {
    /// Mapped LUT per green channel `0..=47` (`None` -> grayscale fallback `[R, R, R]`).
    pub channels: [Option<[[u8; 3]; 256]>; 48],
}

impl RemapLuts {
    /// Build LUTs matching `0x52906a..0x5291f3` from decoded appearance.
    pub fn from_appearance(app: &AvatarAppearance) -> Self {
        let fur_lut = |idx: u8| -> [[u8; 3]; 256] {
            let i = if (idx as usize) < FUR_COLORS.len() { idx as usize } else { 0 };
            build_8stop_lut(&FUR_COLORS[i])
        };
        let hair_lut = |idx: u8| -> [[u8; 3]; 256] {
            let i = if (idx as usize) < HAIR_COLORS.len() { idx as usize } else { 0 };
            build_8stop_lut(&HAIR_COLORS[i])
        };
        let clothes_lut = |idx: u8| -> [[u8; 3]; 256] {
            let i = if (idx as usize) < CLOTHES_COLORS.len() { idx as usize } else { 0 };
            build_8stop_lut(&CLOTHES_COLORS[i])
        };
        let eye_lut = |idx: u8| -> [[u8; 3]; 256] {
            let i = if (idx as usize) < EYE_INDICES.len() { idx as usize } else { 0 };
            let pal_idx = EYE_INDICES[i] as usize;
            let mid = if pal_idx == 0 { [0, 0, 0] } else { MASTER_PALETTE[pal_idx] };
            build_3stop_lut(mid)
        };
        let badge_lut = |idx: u8| -> [[u8; 3]; 256] {
            let i = if (idx as usize) < BADGE_INDICES.len() { idx as usize } else { 0 };
            let pal_idx = BADGE_INDICES[i] as usize;
            let mid = if pal_idx == 0 { [0, 0, 0] } else { MASTER_PALETTE[pal_idx] };
            build_3stop_lut(mid)
        };

        let mut channels: [Option<[[u8; 3]; 256]>; 48] = std::array::from_fn(|_| None);
        // Channel mapping verbatim from 0x52908c..0x5291f3:
        channels[15] = Some(fur_lut(app.fur));          // Fur      -> G=15 (0x8c)
        channels[4] = Some(fur_lut(app.markings));      // Markings -> G=4  (0x60)
        channels[13] = Some(hair_lut(app.hair));        // Hair     -> G=13 (0x84)
        channels[3] = Some(eye_lut(app.eyes));          // Eyes     -> G=3  (0x5c)
        channels[1] = Some(badge_lut(app.badge));       // Badge    -> G=1  (0x54)
        channels[6] = Some(clothes_lut(app.vest));      // Vest     -> G=6  (0x68)
        channels[9] = Some(clothes_lut(app.bracers));   // Bracers  -> G=9  (0x74)
        channels[2] = Some(clothes_lut(app.cape));      // Cape     -> G=2  (0x58)
        channels[14] = Some(clothes_lut(app.boots));    // Boots    -> G=14 (0x88)
        channels[12] = Some(clothes_lut(app.trousers)); // Trousers -> G=12 (0x80)
        channels[10] = Some(fur_lut(app.wings));        // Wings    -> G=10 (0x78)
        channels[7] = Some(clothes_lut(app.accent));    // Accent   -> G=7  (0x6c)

        // FOX5 defines three remap bands that blend between appearance slots. Each channel
        // is one step farther toward the destination color, with the last channel reaching it.
        let fur = fur_lut(app.fur);
        let markings = fur_lut(app.markings);
        let hair = hair_lut(app.hair);
        for step in 1..=8 {
            channels[15 + step] = Some(blend_luts(&fur, &markings, step, 8));
            channels[23 + step] = Some(blend_luts(&fur, &hair, step, 8));
        }
        for step in 1..=16 {
            channels[31 + step] = Some(blend_luts(&markings, &hair, step, 16));
        }
        Self { channels }
    }

    /// Apply Furcadia's `0x529300..0x529403` pixel color remapping to decoded RGBA pixels.
    /// Pixels with `B == 0` and `A != 0` are remapped via `G` channel (`R` is shade `0..=255`).
    pub fn apply_rgba(&self, rgba: &[u8]) -> Vec<u8> {
        let mut out = rgba.to_vec();
        for px in out.chunks_exact_mut(4) {
            let r = px[0];
            let g = px[1];
            let b = px[2];
            let a = px[3];
            if r == 0 && g == 0 && b == 1 {
                px[0] = 0;
                px[1] = 0;
                px[2] = 0;
            } else if b == 0 && a != 0 {
                if g == 255 {
                    px[0] = 0;
                    px[1] = 0;
                    px[2] = 0;
                } else if let Some(Some(lut)) = self.channels.get(g as usize) {
                    let rgb = lut[r as usize];
                    px[0] = rgb[0];
                    px[1] = rgb[1];
                    px[2] = rgb[2];
                } else {
                    px[0] = r;
                    px[1] = r;
                    px[2] = r;
                }
            }
        }
        out
    }
}

fn blend_luts(
    from: &[[u8; 3]; 256],
    to: &[[u8; 3]; 256],
    step: usize,
    steps: usize,
) -> [[u8; 3]; 256] {
    let mut blended = [[0u8; 3]; 256];
    for shade in 0..256 {
        for channel in 0..3 {
            let a = from[shade][channel] as usize;
            let b = to[shade][channel] as usize;
            blended[shade][channel] = ((a * (steps - step) + b * step + steps / 2) / steps) as u8;
        }
    }
    blended
}

fn build_8stop_lut(stops8: &[[u8; 3]; 8]) -> [[u8; 3]; 256] {
    let dark = [
        ((stops8[7][0] as u16 * 4) / 7) as u8,
        ((stops8[7][1] as u16 * 4) / 7) as u8,
        ((stops8[7][2] as u16 * 4) / 7) as u8,
    ];
    let bright = [
        (((stops8[0][0] as u16 + 0x33) * 5) / 6).min(255) as u8,
        (((stops8[0][1] as u16 + 0x33) * 5) / 6).min(255) as u8,
        (((stops8[0][2] as u16 + 0x33) * 5) / 6).min(255) as u8,
    ];
    let pts: [(usize, [u8; 3]); 10] = [
        (0x00, dark),
        (0x18, stops8[7]),
        (0x30, stops8[6]),
        (0x48, stops8[5]),
        (0x60, stops8[4]),
        (0x78, stops8[3]),
        (0x90, stops8[2]),
        (0xa8, stops8[1]),
        (0xc0, stops8[0]),
        (0xff, bright),
    ];
    interpolate_stops(&pts)
}

fn build_3stop_lut(mid: [u8; 3]) -> [[u8; 3]; 256] {
    let pts: [(usize, [u8; 3]); 3] = [(0x00, [0, 0, 0]), (0x80, mid), (0xff, [255, 255, 255])];
    interpolate_stops(&pts)
}

fn interpolate_stops(pts: &[(usize, [u8; 3])]) -> [[u8; 3]; 256] {
    let mut lut = [[0u8; 3]; 256];
    for seg in pts.windows(2) {
        let (x0, c0) = seg[0];
        let (x1, c1) = seg[1];
        if x1 <= x0 {
            continue;
        }
        let span = (x1 - x0) as f64;
        let dr = (c1[0] as f64 - c0[0] as f64) / span;
        let dg = (c1[1] as f64 - c0[1] as f64) / span;
        let db = (c1[2] as f64 - c0[2] as f64) / span;
        for step in 0..=(x1 - x0) {
            let x = x0 + step;
            let f = step as f64;
            lut[x] = [
                (c0[0] as f64 + dr * f).clamp(0.0, 255.0) as u8,
                (c0[1] as f64 + dg * f).clamp(0.0, 255.0) as u8,
                (c0[2] as f64 + db * f).clamp(0.0, 255.0) as u8,
            ];
        }
    }
    lut
}

